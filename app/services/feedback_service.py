from app.core.openai_client import client
import json


async def generate_feedback(
        question: str,
        answer: str,
        field_name: str = None,
        company_name: str = None
):
    field_context = ""
    company_context = ""

    if field_name:
        field_context = f"""
[지원 분야]
{field_name}

* 추가 지시사항:

먼저 현재 질문이 직무 역량, 전공 지식, 프로젝트 경험,
문제 해결 경험, 협업 경험 등 직무 관련 질문인지 판단하라.

직무 관련 질문인 경우에만
지원 분야({field_name})에서 요구되는 핵심 역량,
실무 트렌드, 기술 역량을 참고하여 평가하라.

일반 인성 질문(자기소개, 장단점, 취미, 가치관 등)의 경우에는
지원 분야 정보를 평가에 반영하지 말고
답변 자체의 품질만 평가하라.
"""

    if company_name:
        company_context = f"""
[희망 기업]
{company_name}

* 추가 지시사항:

먼저 현재 면접 질문이 아래 유형 중 무엇인지 판단하라.

1. 일반 인성 질문
- 자기소개
- 성격
- 장단점
- 취미
- 가치관
- 성장 과정
- 최근 관심사
- 기타 개인 특성 확인 질문

2. 직무 관련 질문
- 직무 역량
- 전공 지식
- 프로젝트 경험
- 기술 스택
- 문제 해결 경험
- 협업 경험
- 리더십 경험
- 실무 경험

3. 기업 적합성 질문
- 지원동기
- 입사 후 포부
- 회사 선택 이유
- 기업 문화 적합성
- 해당 기업에서 이루고 싶은 목표

질문이 2번 또는 3번에 해당하는 경우에만
{company_name}의 일반적으로 알려진 인재상,
핵심 가치, 조직 문화, 채용 방향성을 참고하여 평가하라.

질문이 1번에 해당하는 경우에는
기업 정보와 인재상을 평가에 반영하지 말고,
답변 자체의 품질만 평가하라.

기업 적합성은 답변 품질보다 우선하지 말고
보조적인 참고 요소로만 활용하라.
"""

    prompt = f"""
아래는 면접 질문과 지원자의 답변이다.

{field_context}

{company_context}

[질문]
{question}

[답변]
{answer}

너는 냉정한 면접 평가자다.

아래 평가 기준에 따라 답변을 분석하여 점수를 계산하고
점수와 함께 한줄 피드백을 제공하라.

[평가 기준]

1. 질문 적합성 (0~40)
- 질문 의도를 정확히 이해했는가
- 질문에 맞는 핵심 경험 또는 근거가 포함되었는가
- 질문과 관련 없는 내용이 과도하지 않은가

2. 답변 구조 (0~20)
- 답변 흐름이 자연스러운가
- 도입, 설명, 결과가 논리적으로 연결되는가
- 문장이 지나치게 산만하지 않은가

3. 전달력 및 명확성 (0~20)
- 문장이 이해하기 쉬운가
- 핵심 메시지가 명확하게 전달되는가
- 표현이 지나치게 모호하지 않은가

4. 반복 표현 여부 (0~20)
- 같은 단어 또는 문장을 과도하게 반복하지 않았는가
- "음", "약간", "그냥" 등의 습관적 표현이 많은가
- 표현 다양성이 유지되는가

[평가 원칙]

- 답변 자체의 품질을 가장 중요하게 평가하라.
- 기업 적합성과 직무 적합성은 보조 요소로만 활용하라.
- 기업명 또는 지원 분야가 제공되더라도 점수에 과도하게 반영하지 말 것.
- 일반 인성 질문은 답변 품질만 중심으로 평가할 것.

[점수 기준]

- 90~100점:
질문 의도를 정확히 파악했고 답변 구조와 전달력이 매우 우수함

- 80~89점:
전반적으로 우수하나 일부 표현 또는 구체성이 부족함

- 70~79점:
기본적인 답변은 가능하지만 핵심 근거 또는 논리성이 부족함

- 60~69점:
반복 표현이 많거나 답변 핵심 내용이 일부 누락됨

- 0~59점:
질문과 관련성이 낮거나 전달력이 크게 부족함

피드백은 1문장으로 작성하라.

반드시 아래 JSON 형식으로만 응답해라.

{{
    "score": 85,
    "feedback": "질문 의도에 적절하게 답변했지만 구체적인 근거가 다소 부족합니다."
}}
"""

    response = client.chat.completions.create(
        model="gpt-4.1-mini",
        messages=[
            {
                "role": "system",
                "content": (
                    "너는 냉정한 면접 평가자다. "
                    "답변 자체의 품질을 우선 평가하며 "
                    "기업 적합성과 직무 적합성은 보조 요소로만 활용한다. "
                    "항상 JSON 객체 형식으로만 응답한다."
                )
            },
            {
                "role": "user",
                "content": prompt
            }
        ],
        response_format={"type": "json_object"}
    )

    result_text = response.choices[0].message.content

    try:
        result = json.loads(result_text)

    except json.JSONDecodeError:
        result = {
            "score": 0,
            "feedback": "피드백 생성 실패"
        }

    return result